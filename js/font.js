export const LINE_H = 10;

export function textWidth(str) {
  let w = 0;
  for (const ch of str) {
    const g = G[ch] || G['?'];
    w += g.length + 1;
  }
  return Math.max(0, w - 1);
}

const cache = new Map();

function glyphCanvas(ch, color) {
  const key = ch + color;
  let c = cache.get(key);
  if (c) return c;
  const cols = G[ch] || G['?'];
  c = makeCanvas(cols.length, 8);
  const g = ctxOf(c);
  g.fillStyle = color;
  for (let x = 0; x < cols.length; x++) {
    for (let y = 0; y < 8; y++) {
      if (cols[x] & (1 << y)) g.fillRect(x, y, 1, 1);
    }
  }
  cache.set(key, c);
  return c;
}

/** Draw text at x,y (top-left). Optional 1px drop shadow colour. */
export function drawText(g, str, x, y, color = '#fff', shadow = null) {
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of str) {
    const cols = G[ch] || G['?'];
    if (ch !== ' ') {
      if (shadow) {
        const s = glyphCanvas(ch, shadow);
        g.drawImage(s, cx + 1, cy + 1);
        g.drawImage(s, cx, cy + 1);
      }
      g.drawImage(glyphCanvas(ch, color), cx, cy);
    }
    cx += cols.length + 1;
  }
  return cx - Math.round(x);
}

export function drawTextCentered(g, str, cx, y, color, shadow) {
  return drawText(g, str, Math.round(cx - textWidth(str) / 2), y, color, shadow);
}
